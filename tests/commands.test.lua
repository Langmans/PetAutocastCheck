-- /pac and the kite and tank key bindings.

test("/pac alone, or anything unknown, shows the status and the commands", function()
    local client = NewClient():login():slash("")
    ok(client:printedContains("Mode solo (picked by the addon). Watching Growl on, Cower on, reminder in combat on."))
    ok(client:printedContains("Toast for 6 s at scale 1.00, sound pet's call, debug off."))
    ok(client:printedContains("/pac kite [on|off], /pac tank [on|off]"))
    client.printed = {}
    client:slash("nonsense")
    ok(client:printedContains("Commands:"))
end)

test("the status names the mode in force and who chose it", function()
    local client = NewClient():login():group(true):slash("")
    ok(client:printedContains("Mode dungeon (picked by the addon)."))
    client:slash("tank"):slash("")
    ok(client:printedContains("Mode tank (chosen by you)."))
end)

test("/pac on another class says nothing is watched", function()
    local client = NewClient({ class = "MAGE" }):login():slash("")
    ok(client:printedContains("Only hunter pets have Growl and Cower"))
end)

test("/pac kite toggles, or takes on and off, and checks again at once", function()
    local client = NewClient():login()
    client:slash("kite")
    eq(Saved().mode, "kite")
    ok(client:printedContains("Kite mode on: Growl off, Cower on."))
    eq(client:toastTitle(), "Growl is on autocast", "no wait for the pet bar")
    client:slash("kite")
    eq(Saved().mode, "auto")
    client:slash("kite ON")
    eq(Saved().mode, "kite")
    client:slash("kite off")
    eq(Saved().mode, "auto")
    ok(client:printedContains("Kite mode off: solo or dungeon mode again, as fits."))
end)

test("/pac tank takes over from kite and back to automatic when switched off", function()
    local client = NewClient():login():slash("kite"):slash("tank")
    eq(Saved().mode, "tank")
    ok(client:printedContains("Tank mode on: Growl on, Cower off."))
    client.printed = {}
    client:slash("kite off")
    eq(Saved().mode, "tank", "kite was not on, so nothing changes")
    eq(#client.printed, 0)
    client:slash("tank off")
    eq(Saved().mode, "auto")
    ok(client:printedContains("Tank mode off: solo or dungeon mode again, as fits."))
end)

test("/pac kite on in a macro pressed again and again only speaks when it changes", function()
    local client = NewClient():login():slash("kite on")
    local printed = #client.printed
    client:slash("kite on"):slash("kite on")
    eq(#client.printed, printed)
    eq(Saved().mode, "kite")
end)

test("the key bindings toggle kite and tank mode and have names", function()
    NewClient():login()
    PetAutocastCheck_ToggleKite()
    eq(Saved().mode, "kite")
    PetAutocastCheck_ToggleTank()
    eq(Saved().mode, "tank")
    PetAutocastCheck_ToggleTank()
    eq(Saved().mode, "auto")
    eq(BINDING_HEADER_PETAUTOCASTCHECK, "Pet Autocast Check")
    eq(BINDING_NAME_PETAUTOCASTCHECK_KITE, "Toggle kite mode")
    eq(BINDING_NAME_PETAUTOCASTCHECK_TANK, "Toggle tank mode")
end)

test("/pac growl, cower and remind take on and off", function()
    local client = NewClient():login()
    client:slash("growl off")
    eq(Saved().growl, false)
    ok(client:printedContains("Growl is not watched."))
    client:slash("cower off")
    eq(Saved().cower, false)
    client:slash("remind off")
    eq(Saved().remind, false)
    client:slash("growl on"):slash("cower on"):slash("remind on")
    eq(Saved().growl, true)
    eq(Saved().cower, true)
    eq(Saved().remind, true)
    ok(client:printedContains("toasts again when combat starts"))
    client.printed = {}
    client:slash("growl maybe")
    ok(client:printedContains("Commands:"), "anything else shows the status")
end)

test("/pac growl on in a dungeon group toasts at once", function()
    local client = NewClient({ savedDB = { growl = false, cower = false } }):login():group(true)
    eq(client.toast.shown, false)
    client:slash("growl on")
    eq(client:toastTitle(), "Growl is on autocast")
end)

test("/pac test shows a toast of each kind without touching real ones", function()
    local client = NewClient():login():slash("test")
    eq(client:toastTitle(), "Growl is on autocast")
    eq(client.toast.Reason.text, "In a dungeon group the tank holds the mobs: Growl off, Cower on.")
    client.ns.HideToast()
    client:slash("test cower")
    eq(client:toastTitle(), "Cower is on autocast")
    client.ns.HideToast()
    client:slash("test kite")
    eq(client:toastTitle(), "Cower is not on autocast")
    client.ns.HideToast()
    client:slash("test tank")
    eq(client:toastTitle(), "Growl is not on autocast")
    client:group(true)
    client.ns.HideToast()
    eq(client:toastTitle(), "Growl is on autocast", "the real problem still has its own toast")
end)

